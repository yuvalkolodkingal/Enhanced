package com.kolodkingal.enhanced.hydra;

import com.kolodkingal.enhanced.world.HydraOutpostPlan;
import net.minecraft.core.BlockPos;
import net.minecraft.core.HolderLookup;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.nbt.ListTag;
import net.minecraft.nbt.NbtUtils;
import net.minecraft.nbt.Tag;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.block.Rotation;
import net.minecraft.world.level.saveddata.SavedData;
import net.minecraft.world.phys.AABB;
import org.jetbrains.annotations.Nullable;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collection;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;

/**
 * The Hydra outposts of one dimension that a player has come near (3.6, the plan's 15.4), saved with the world ({@code
 * data/enhanced_hydra_outposts.dat} of the dimension): for each, keyed by the chunk of its structure start, where its
 * template lies and how it was turned, which soldier holds each {@link Post} and when a post's soldier died, and its
 * alarm. Nothing of this is in the template, so outposts generated by 3.3 get their garrison too.
 */
public final class HydraOutposts extends SavedData {
    public static final String NAME = "enhanced_hydra_outposts";
    /** "Never": a post whose soldier has not died. */
    public static final long NEVER = Long.MIN_VALUE;

    private final Map<Long, Outpost> outposts = new LinkedHashMap<>();

    public static SavedData.Factory<HydraOutposts> factory() {
        return new SavedData.Factory<>(HydraOutposts::new, HydraOutposts::load, null);
    }

    /** The outposts of this level, made empty if there are none yet. */
    public static HydraOutposts get(ServerLevel level) {
        return level.getDataStorage().computeIfAbsent(factory(), NAME);
    }

    /** The outposts of this level if it has a record (nothing is made: what every tick asks first), else null. */
    @Nullable
    public static HydraOutposts peek(ServerLevel level) {
        return level.getDataStorage().get(factory(), NAME);
    }

    private static HydraOutposts load(CompoundTag tag, HolderLookup.Provider registries) {
        HydraOutposts store = new HydraOutposts();
        for (Tag t : tag.getList("outposts", Tag.TAG_COMPOUND)) {
            Outpost outpost = Outpost.read((CompoundTag) t);
            outpost.store = store;
            store.outposts.put(outpost.key, outpost);
        }
        return store;
    }

    @Override
    public CompoundTag save(CompoundTag tag, HolderLookup.Provider registries) {
        ListTag list = new ListTag();
        for (Outpost outpost : outposts.values()) {
            list.add(outpost.write());
        }
        tag.put("outposts", list);
        return tag;
    }

    /** The outpost of this key (its structure start's chunk), or null if none was registered. */
    @Nullable
    public Outpost byKey(long key) {
        return outposts.get(key);
    }

    /**
     * The outpost of this key, registered (with no soldiers yet) if it is new: its template lies at {@code
     * templatePosition}, turned {@code rotation}.
     */
    public Outpost register(long key, BlockPos templatePosition, Rotation rotation) {
        Outpost outpost = outposts.get(key);
        if (outpost == null) {
            outpost = new Outpost(key, templatePosition, rotation, 1.0F);
            add(outpost);
        }
        return outpost;
    }

    /** Adds an outpost made by hand (a test's shrunken one); one of the same key is replaced. */
    public void add(Outpost outpost) {
        outpost.store = this;
        outposts.put(outpost.key, outpost);
        setDirty();
    }

    /** Forgets an outpost (a test's, when it ends). */
    public void remove(long key) {
        if (outposts.remove(key) != null) {
            setDirty();
        }
    }

    public Collection<Outpost> all() {
        return Collections.unmodifiableCollection(outposts.values());
    }

    /** The outpost whose compound holds {@code pos} (its template's box, grown by {@code margin}), or null. */
    @Nullable
    public Outpost at(BlockPos pos, double margin) {
        for (Outpost outpost : outposts.values()) {
            if (outpost.box().inflate(margin).contains(pos.getX() + 0.5, pos.getY() + 0.5, pos.getZ() + 0.5)) {
                return outpost;
            }
        }
        return null;
    }

    /**
     * One outpost: where its template lies and how it is turned, its posts' soldiers and deaths, its alarm. A test's
     * outpost may be {@linkplain #scale shrunken} round its centre so that its posts fit in a test's arena.
     */
    public static final class Outpost {
        private final long key;
        private final BlockPos templatePosition;
        private final Rotation rotation;
        /** 1 for a real outpost; less for a test's, drawn in round its centre, everything at the centre's height. */
        private final float scale;
        private final UUID[] soldiers = new UUID[Post.COUNT];
        private final long[] diedGame = new long[Post.COUNT];
        private final long[] diedDay = new long[Post.COUNT];
        /** When a post's soldier was last found missing, not dead (unloaded or lost); not saved. */
        final long[] missingSince = new long[Post.COUNT];
        /** The alarm: until when it sounds (game time), -1 for off. */
        long alarmUntil = -1L;
        /** When the reinforcements of the running alarm come (game time), -1 for none. */
        long waveAt = -1L;
        /** The in-game day of the waves counted in {@link #waves}. */
        long waveDay = -1L;
        int waves;
        /** Until when the radio console has the alarm switched off (game time), -1 for never. */
        long silencedUntil = -1L;
        /** When a soldier of this outpost last had an intruder in his sights (game time). */
        long lastIntruder = -1L;
        boolean lampsLit;
        final List<UUID> reinforcements = new ArrayList<>();
        /** The soldier running to a console to raise the alarm, or null; not saved. */
        @Nullable
        UUID runner;
        @Nullable
        private HydraOutposts store;

        public Outpost(long key, BlockPos templatePosition, Rotation rotation, float scale) {
            this.key = key;
            this.templatePosition = templatePosition.immutable();
            this.rotation = rotation;
            this.scale = scale;
            Arrays.fill(diedGame, NEVER);
            Arrays.fill(diedDay, NEVER);
            Arrays.fill(missingSince, NEVER);
        }

        public long key() {
            return key;
        }

        public BlockPos templatePosition() {
            return templatePosition;
        }

        public Rotation rotation() {
            return rotation;
        }

        public float scale() {
            return scale;
        }

        /** Whether this is a real outpost (not a test's shrunken one). */
        public boolean real() {
            return scale >= 1.0F;
        }

        void changed() {
            if (store != null) {
                store.setDirty();
            }
        }

        /** Where a template-relative point of this outpost is in the world. */
        public BlockPos where(BlockPos local) {
            BlockPos world = HydraOutpostPlan.toWorld(local, rotation, templatePosition);
            if (real()) {
                return world;
            }
            BlockPos centre = HydraOutpostPlan.toWorld(HydraOutpostPlan.CENTRE, rotation, templatePosition);
            return new BlockPos(centre.getX() + Math.round((world.getX() - centre.getX()) * scale), centre.getY(),
                    centre.getZ() + Math.round((world.getZ() - centre.getZ()) * scale));
        }

        /** The middle of the compound (the leash, the "nobody near" of a respawn and the reach of the alarm). */
        public BlockPos centre() {
            return where(HydraOutpostPlan.CENTRE);
        }

        /** The template's box in the world (for a test's outpost: its shrunken footprint, two blocks high). */
        public AABB box() {
            BlockPos a = where(BlockPos.ZERO);
            BlockPos b = where(new BlockPos(HydraOutpostPlan.SIZE.getX() - 1, HydraOutpostPlan.SIZE.getY() - 1,
                    HydraOutpostPlan.SIZE.getZ() - 1));
            double top = real() ? Math.max(a.getY(), b.getY()) + 1 : a.getY() + 2;
            return new AABB(Math.min(a.getX(), b.getX()), Math.min(a.getY(), b.getY()), Math.min(a.getZ(), b.getZ()),
                    Math.max(a.getX(), b.getX()) + 1, top, Math.max(a.getZ(), b.getZ()) + 1);
        }

        /** The soldier who holds post {@code index}, or null. */
        @Nullable
        public UUID soldier(int index) {
            return soldiers[index];
        }

        void setSoldier(int index, @Nullable UUID id) {
            soldiers[index] = id;
            missingSince[index] = NEVER;
            if (id != null) {
                diedGame[index] = NEVER;
                diedDay[index] = NEVER;
            }
            changed();
        }

        /** When the soldier of post {@code index} died (game time), or {@link #NEVER}. */
        public long diedGame(int index) {
            return diedGame[index];
        }

        /** The day time when the soldier of post {@code index} died, or {@link #NEVER}. */
        public long diedDay(int index) {
            return diedDay[index];
        }

        void died(int index, long game, long day) {
            diedGame[index] = game;
            diedDay[index] = day;
            missingSince[index] = NEVER;
            changed();
        }

        /** The post that {@code id} holds, or -1. */
        public int postOf(UUID id) {
            for (int i = 0; i < soldiers.length; i++) {
                if (id.equals(soldiers[i])) {
                    return i;
                }
            }
            return -1;
        }

        /** Whether the alarm sounds now. */
        public boolean alarmOn(long now) {
            return alarmUntil > now;
        }

        /** Whether the radio console has the alarm switched off now. */
        public boolean silenced(long now) {
            return silencedUntil > now;
        }

        /** The waves of reinforcements this outpost has called on in-game day {@code day}. */
        public int waves(long day) {
            return waveDay == day ? waves : 0;
        }

        /** When the reinforcements of the running alarm come (game time), or -1. */
        public long waveAt() {
            return waveAt;
        }

        public List<UUID> reinforcements() {
            return Collections.unmodifiableList(reinforcements);
        }

        public boolean lampsLit() {
            return lampsLit;
        }

        CompoundTag write() {
            CompoundTag tag = new CompoundTag();
            tag.putLong("key", key);
            tag.put("template", NbtUtils.writeBlockPos(templatePosition));
            tag.putString("rotation", rotation.name());
            tag.putFloat("scale", scale);
            ListTag posts = new ListTag();
            for (int i = 0; i < Post.COUNT; i++) {
                CompoundTag p = new CompoundTag();
                p.putInt("i", i);
                if (soldiers[i] != null) {
                    p.putUUID("id", soldiers[i]);
                }
                p.putLong("died", diedGame[i]);
                p.putLong("diedDay", diedDay[i]);
                posts.add(p);
            }
            tag.put("posts", posts);
            tag.putLong("alarmUntil", alarmUntil);
            tag.putLong("waveAt", waveAt);
            tag.putLong("waveDay", waveDay);
            tag.putInt("waves", waves);
            tag.putLong("silencedUntil", silencedUntil);
            tag.putLong("lastIntruder", lastIntruder);
            tag.putBoolean("lampsLit", lampsLit);
            ListTag extra = new ListTag();
            for (UUID id : reinforcements) {
                extra.add(NbtUtils.createUUID(id));
            }
            tag.put("reinforcements", extra);
            return tag;
        }

        static Outpost read(CompoundTag tag) {
            Rotation rotation;
            try {
                rotation = Rotation.valueOf(tag.getString("rotation"));
            } catch (IllegalArgumentException e) {
                rotation = Rotation.NONE;
            }
            BlockPos template = NbtUtils.readBlockPos(tag, "template").orElse(BlockPos.ZERO);
            float scale = tag.contains("scale") ? tag.getFloat("scale") : 1.0F;
            Outpost outpost = new Outpost(tag.getLong("key"), template, rotation, scale);
            for (Tag t : tag.getList("posts", Tag.TAG_COMPOUND)) {
                CompoundTag p = (CompoundTag) t;
                int i = p.getInt("i");
                if (i < 0 || i >= Post.COUNT) {
                    continue;
                }
                if (p.hasUUID("id")) {
                    outpost.soldiers[i] = p.getUUID("id");
                }
                outpost.diedGame[i] = p.getLong("died");
                outpost.diedDay[i] = p.getLong("diedDay");
            }
            outpost.alarmUntil = tag.getLong("alarmUntil");
            outpost.waveAt = tag.getLong("waveAt");
            outpost.waveDay = tag.getLong("waveDay");
            outpost.waves = tag.getInt("waves");
            outpost.silencedUntil = tag.getLong("silencedUntil");
            outpost.lastIntruder = tag.getLong("lastIntruder");
            outpost.lampsLit = tag.getBoolean("lampsLit");
            for (Tag t : tag.getList("reinforcements", Tag.TAG_INT_ARRAY)) {
                outpost.reinforcements.add(NbtUtils.loadUUID(t));
            }
            return outpost;
        }
    }
}
