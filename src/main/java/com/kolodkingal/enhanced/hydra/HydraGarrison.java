/**
 * The garrisons of the Hydra outposts (3.6, the plan's 15.4). Not natural spawning: every 40 ticks per player, the
 * Hydra outposts within {@code [hydra] activateRadius} (64) of him are found by their structure starts (cached per
 * chunk for a while), registered ({@link HydraOutposts}, so outposts generated by 3.3 get a garrison too) and their
 * posts filled ({@link #fill}): a post with nobody yet, or whose soldier is due again, gets a soldier at his post, out
 * of every player's sight (not within 12 blocks, not in a player's view; else at the next check). The stand-in
 * pillagers of 3.3 are sent away from the compound.
 *
 * <p>Respawn ({@code respawn}): {@code days} — a dead soldier's post fills again after {@code respawnDays} (3) in-game
 * days, only while no player is within 64 blocks of the outpost ("they came back while you were away"); {@code never}
 * — a cleared outpost stays empty; {@code always} — every check fills it. Caps: {@code maxPerOutpost} (14) alive at
 * one outpost (posts and reinforcements), {@code maxLoaded} (80) in the dimension; {@code enabled} false stops it;
 * Peaceful has none.
 */
public final class HydraGarrison {
    public static final ResourceKey<Structure> OUTPOST = ResourceKey.create(Registries.STRUCTURE,
            Enhanced.id("hydra_outpost"));
    /** How often (ticks) each player's surroundings are checked. */
    public static final int PERIOD = 40;
    /** Nobody within this many blocks of an outpost's centre: a dead post may come back (respawn {@code days}). */
    public static final double NOBODY_NEAR = 64.0;
    /** A soldier never appears this near a player. */
    public static final double NOT_WITHIN = 12.0;
    /** A soldier missing (not dead) this long while his outpost is loaded has been lost: his post is free. */
    public static final int LOST_AFTER = 6000;
    /** How long a chunk's list of outposts near it is kept (ticks). */
    private static final int CACHE_TICKS = 600;

    /** Per dimension: a player's chunk → the outposts' start chunks near it, and until when that is known. */
    private static final Map<ResourceKey<Level>, Map<Long, Found>> CACHE = new HashMap<>();

    private record Found(long until, LongSet starts) {
    }

    // ---- the numbers ----

    static boolean enabled() {
        return !EnhancedConfig.SPEC.isLoaded() || HydraConfig.ENABLED.get();
    }

    static int garrisonSize() {
        return Math.min(Post.COUNT, EnhancedConfig.SPEC.isLoaded() ? HydraConfig.GARRISON_SIZE.get() : 9);
    }

    static HydraConfig.Respawn respawn() {
        return EnhancedConfig.SPEC.isLoaded() ? HydraConfig.RESPAWN.get() : HydraConfig.Respawn.DAYS;
    }

    static int respawnDays() {
        return EnhancedConfig.SPEC.isLoaded() ? HydraConfig.RESPAWN_DAYS.get() : 3;
    }

    static int activateRadius() {
        return EnhancedConfig.SPEC.isLoaded() ? HydraConfig.ACTIVATE_RADIUS.get() : 64;
    }

    static int maxPerOutpost() {
        return EnhancedConfig.SPEC.isLoaded() ? HydraConfig.MAX_PER_OUTPOST.get() : 14;
    }

    static int maxLoaded() {
        return EnhancedConfig.SPEC.isLoaded() ? HydraConfig.MAX_LOADED.get() : 80;
    }

    // ---- the player's tick ----

    /** One player's tick (the shared player tick calls it): the outposts near him are filled when due. */
    public static void tick(ServerPlayer player) {
        if ((player.tickCount + player.getId()) % PERIOD != 0 || player.isSpectator()) {
            return;
        }
        ServerLevel level = player.serverLevel();
        if (!enabled() || level.getDifficulty() == Difficulty.PEACEFUL) {
            return;
        }
        LongSet starts = startsNear(level, player.blockPosition());
        if (starts.isEmpty()) {
            return;
        }
        HydraOutposts store = HydraOutposts.get(level);
        int radius = activateRadius();
        for (long start : starts) {
            HydraOutposts.Outpost outpost = store.byKey(start);
            if (outpost == null) {
                outpost = resolve(level, store, start);
                if (outpost == null) {
                    continue;
                }
            }
            if (horizontalDistance(outpost.box(), player.position()) > radius) {
                continue;
            }
            sendPillagersAway(level, outpost);
            fill(level, outpost, level.getGameTime(), level.getDayTime());
            changeShift(level, outpost);
        }
    }

    /** The start chunks of the Hydra outposts referenced by the loaded chunks round {@code pos} (cached a while). */
    static LongSet startsNear(ServerLevel level, BlockPos pos) {
        long chunk = ChunkPos.asLong(pos.getX() >> 4, pos.getZ() >> 4);
        long now = level.getGameTime();
        Map<Long, Found> cache = CACHE.computeIfAbsent(level.dimension(), k -> new HashMap<>());
        Found found = cache.get(chunk);
        if (found != null && found.until() > now) {
            return found.starts();
        }
        if (cache.size() > 4096) {
            cache.entrySet().removeIf(e -> e.getValue().until() <= now);
        }
        LongSet starts = new LongOpenHashSet();
        Structure structure = level.registryAccess().registryOrThrow(Registries.STRUCTURE).get(OUTPOST);
        if (structure != null) {
            int reach = (activateRadius() + 32) >> 4;
            int cx = pos.getX() >> 4;
            int cz = pos.getZ() >> 4;
            for (int dx = -reach; dx <= reach; dx++) {
                for (int dz = -reach; dz <= reach; dz++) {
                    LevelChunk c = level.getChunkSource().getChunkNow(cx + dx, cz + dz);
                    if (c != null) {
                        starts.addAll(c.getReferencesForStructure(structure));
                    }
                }
            }
        }
        cache.put(chunk, new Found(now + CACHE_TICKS, starts));
        return starts;
    }

    /** Registers the outpost whose structure start is in chunk {@code start}, from its piece; null if not loaded. */
    @Nullable
    static HydraOutposts.Outpost resolve(ServerLevel level, HydraOutposts store, long start) {
        Structure structure = level.registryAccess().registryOrThrow(Registries.STRUCTURE).get(OUTPOST);
        if (structure == null) {
            return null;
        }
        ChunkPos at = new ChunkPos(start);
        ChunkAccess chunk = level.getChunk(at.x, at.z, ChunkStatus.STRUCTURE_STARTS, false);
        StructureStart found = chunk == null ? null : chunk.getStartForStructure(structure);
        if (found == null || !found.isValid()) {
            return null;
        }
        for (StructurePiece piece : found.getPieces()) {
            if (piece instanceof TemplateSitePiece site) {
                return store.register(start, site.templatePosition(), site.placeSettings().getRotation());
            }
        }
        return null;
    }

    private static double horizontalDistance(AABB box, Vec3 pos) {
        double dx = Math.max(0.0, Math.max(box.minX - pos.x, pos.x - box.maxX));
        double dz = Math.max(0.0, Math.max(box.minZ - pos.z, pos.z - box.maxZ));
        return Math.sqrt(dx * dx + dz * dz);
    }

    // ---- filling the posts ----

    /**
     * Fills the posts of {@code outpost} that are empty or due, at game time {@code game} and day time {@code day}
     * (the respawn counts by whichever has run further, so {@code /time add} brings them back too).
     *
     * @return the soldiers who appeared
     */
    public static List<HydraSoldierEntity> fill(ServerLevel level, HydraOutposts.Outpost outpost, long game, long day) {
        List<HydraSoldierEntity> came = new java.util.ArrayList<>();
        if (!enabled() || level.getDifficulty() == Difficulty.PEACEFUL) {
            return came;
        }
        int posts = garrisonSize();
        for (int i = 0; i < posts; i++) {
            UUID id = outpost.soldier(i);
            if (id != null) {
                Entity e = level.getEntity(id);
                if (e instanceof HydraSoldierEntity soldier && soldier.isAlive()) {
                    outpost.missingSince[i] = HydraOutposts.NEVER;
                    continue;
                }
                if (e == null && outpost.diedGame(i) == HydraOutposts.NEVER) {
                    // Not dead: unloaded, or lost. Free the post only once its place has been loaded a long while.
                    if (!level.isLoaded(spawnPos(level, outpost, Post.byIndex(i)))) {
                        continue;
                    }
                    if (outpost.missingSince[i] == HydraOutposts.NEVER) {
                        outpost.missingSince[i] = game;
                    }
                    if (game - outpost.missingSince[i] < LOST_AFTER) {
                        continue;
                    }
                    outpost.setSoldier(i, null);
                }
            }
            if (!due(level, outpost, i, game, day)) {
                continue;
            }
            if (!roomFor(level, outpost)) {
                break;
            }
            Post post = Post.byIndex(i);
            BlockPos at = spawnPos(level, outpost, post);
            if (!level.isLoaded(at) || !unseen(level, Vec3.atBottomCenterOf(at), NOT_WITHIN)) {
                continue;
            }
            HydraSoldierEntity soldier = spawn(level, outpost, i, at);
            if (soldier != null) {
                came.add(soldier);
            }
        }
        return came;
    }

    /** Whether post {@code i}, empty, is due a soldier now. */
    public static boolean due(ServerLevel level, HydraOutposts.Outpost outpost, int i, long game, long day) {
        if (outpost.diedGame(i) == HydraOutposts.NEVER) {
            return outpost.soldier(i) == null;
        }
        return switch (respawn()) {
            case NEVER -> false;
            case ALWAYS -> true;
            case DAYS -> {
                long wait = respawnDays() * 24000L;
                long elapsed = Math.max(game - outpost.diedGame(i), day - outpost.diedDay(i));
                yield elapsed >= wait && !playerNear(level, outpost, NOBODY_NEAR);
            }
        };
    }

    /** Whether a player (not a spectator) is within {@code radius} of the outpost's centre. */
    public static boolean playerNear(ServerLevel level, HydraOutposts.Outpost outpost, double radius) {
        Vec3 centre = Vec3.atCenterOf(outpost.centre());
        for (Player player : level.players()) {
            if (!player.isSpectator() && player.distanceToSqr(centre) <= radius * radius) {
                return true;
            }
        }
        return false;
    }

    /** Where post {@code post}'s soldier appears: his point, or his patrol's first corner (on the ground outside). */
    public static BlockPos spawnPos(ServerLevel level, HydraOutposts.Outpost outpost, Post post) {
        BlockPos at = outpost.where(post.isOfficer() && !level.isDay() ? HydraOutpostPlan.RADIO_POST
                : post.spawnPoint());
        if (post.route() != null && post.route().onSurface() && outpost.real() && level.isLoaded(at)) {
            at = new BlockPos(at.getX(), level.getHeight(Heightmap.Types.MOTION_BLOCKING_NO_LEAVES, at.getX(),
                    at.getZ()), at.getZ());
        }
        return at;
    }

    /** Whether one more Hydra may appear at {@code outpost}: under its cap and the dimension's. */
    static boolean roomFor(ServerLevel level, HydraOutposts.Outpost outpost) {
        int here = 0;
        for (int i = 0; i < Post.COUNT; i++) {
            UUID id = outpost.soldier(i);
            if (id != null && level.getEntity(id) instanceof HydraSoldierEntity s && s.isAlive()) {
                here++;
            }
        }
        for (UUID id : outpost.reinforcements()) {
            if (level.getEntity(id) instanceof HydraSoldierEntity s && s.isAlive()) {
                here++;
            }
        }
        return here < maxPerOutpost() && loaded(level) < maxLoaded();
    }

    /** How many Hydra (soldiers and officers) are loaded in the dimension. */
    public static int loaded(ServerLevel level) {
        return level.getEntities(EntityTypeTest.forClass(HydraSoldierEntity.class), Entity::isAlive).size();
    }

    /** Makes the soldier of post {@code index} at {@code at}. */
    @Nullable
    public static HydraSoldierEntity spawn(ServerLevel level, HydraOutposts.Outpost outpost, int index, BlockPos at) {
        Post post = Post.byIndex(index);
        EntityType<? extends HydraSoldierEntity> type = post.isOfficer() ? ModEntities.HYDRA_OFFICER.get()
                : ModEntities.HYDRA_SOLDIER.get();
        HydraSoldierEntity soldier = type.create(level);
        if (soldier == null) {
            return null;
        }
        Rank rank = post.isOfficer() ? Rank.RIFLEMAN : post.rank();
        soldier.setRank(rank, level.random.nextInt(post.isOfficer() ? HydraOfficerEntity.SKINS : rank.skins()));
        soldier.belongTo(outpost, index, false);
        BlockPos centre = outpost.centre();
        float yaw = (float) Math.toDegrees(Math.atan2(-(at.getX() - centre.getX()), at.getZ() - centre.getZ()));
        soldier.moveTo(at.getX() + 0.5, at.getY(), at.getZ() + 0.5, yaw, 0.0F);
        soldier.setYHeadRot(yaw);
        soldier.yBodyRot = yaw;
        level.addFreshEntity(soldier);
        outpost.setSoldier(index, soldier.getUUID());
        return soldier;
    }

    /**
     * Whether nobody would see something appear (or vanish) at {@code pos}: no player within {@code within} blocks,
     * and none who has it in his view with nothing in the way.
     */
    public static boolean unseen(ServerLevel level, Vec3 pos, double within) {
        Vec3 middle = pos.add(0.0, 1.0, 0.0);
        for (Player player : level.players()) {
            if (player.isSpectator()) {
                continue;
            }
            double d = player.distanceToSqr(middle);
            if (d < within * within) {
                return false;
            }
            if (d > 96.0 * 96.0 || !HydraSenses.inCone(player.getYHeadRot(), player.getEyePosition(), middle)) {
                continue;
            }
            HitResult hit = level.clip(new ClipContext(player.getEyePosition(), middle, ClipContext.Block.VISUAL,
                    ClipContext.Fluid.NONE, player));
            if (hit.getType() == HitResult.Type.MISS) {
                return false;
            }
        }
        return true;
    }

    /** The 3.3 stand-ins: pillagers in the compound (not in a raid) are sent away. */
    public static int sendPillagersAway(ServerLevel level, HydraOutposts.Outpost outpost) {
        List<Pillager> stand = level.getEntitiesOfClass(Pillager.class, outpost.box().inflate(2.0, 4.0, 2.0),
                p -> p.getCurrentRaid() == null && !p.hasCustomName() && !p.isPatrolLeader());
        for (Pillager pillager : stand) {
            pillager.discard();
        }
        return stand.size();
    }

    /** The officer goes on duty in the radio room at night and the command room by day, while nobody sees it. */
    static void changeShift(ServerLevel level, HydraOutposts.Outpost outpost) {
        HydraOfficerEntity officer = HydraAlarm.officer(level, outpost);
        if (officer == null || officer.getTarget() != null || HydraLoyalty.isTraitor(officer)) {
            return;
        }
        BlockPos post = officer.postPos();
        if (post == null || officer.distanceToSqr(Vec3.atBottomCenterOf(post)) < 36.0) {
            return;
        }
        if (unseen(level, officer.position(), 24.0) && unseen(level, Vec3.atBottomCenterOf(post), 24.0)) {
            officer.getNavigation().stop();
            officer.teleportTo(post.getX() + 0.5, post.getY(), post.getZ() + 0.5);
        }
    }

    // ---- deaths ----

    /** A soldier died: his post's death is noted (it waits for its respawn); a reinforcement is gone for good. */
    static void died(ServerLevel level, HydraSoldierEntity soldier) {
        HydraOutposts.Outpost outpost = soldier.outpost();
        if (outpost == null) {
            return;
        }
        if (soldier.isReinforcement()) {
            outpost.reinforcements.remove(soldier.getUUID());
            outpost.changed();
            return;
        }
        int index = outpost.postOf(soldier.getUUID());
        if (index >= 0) {
            outpost.died(index, level.getGameTime(), level.getDayTime());
        }
        if (soldier.isOfficer()) {
            HydraAlarm.officerDown(level, outpost);
        }
        if (soldier.getUUID().equals(outpost.runner)) {
            outpost.runner = null;
        }
    }

    /** A soldier was taken away without dying (Peaceful, a command, a reinforcement leaving): his post is free. */
    static void discarded(ServerLevel level, HydraSoldierEntity soldier) {
        HydraOutposts.Outpost outpost = soldier.outpost();
        if (outpost == null) {
            return;
        }
        if (soldier.isReinforcement()) {
            if (outpost.reinforcements.remove(soldier.getUUID())) {
                outpost.changed();
            }
            return;
        }
        int index = outpost.postOf(soldier.getUUID());
        if (index >= 0 && soldier.isAlive()) {
            outpost.setSoldier(index, null);
        }
    }

    /** Forgets the caches (the server stops). */
    public static void clear() {
        CACHE.clear();
    }

    private HydraGarrison() {
    }
}
